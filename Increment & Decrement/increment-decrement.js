let a = 10;

// Pre-Increment
// Phle value increase hogi, phir use hogi
console.log("Pre-Increment:", ++a);
console.log("Value of a:", a);

a = 10;

// Post-Increment
// Pehle current value use hogi, phir increase hogi
console.log("Post-Increment:", a++);
console.log("Value of a:", a);

a = 10;

// Pre-Decrement
// Pehle value decrease hogi, phir use hogi
console.log("Pre-Decrement:", --a);
console.log("Value of a:", a);

a = 10;

// Post-Decrement
// Pehle current value use hogi, phir decrease hogi
console.log("Post-Decrement:", a--);
console.log("Value of a:", a);