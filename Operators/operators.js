let a = 10;
let b = 3;

console.log("Addition:", a+b);
console.log("Subtraction:", a-b);
console.log("Multiplication:", a*b);
console.log("Division:", a/b);
console.log("Remainder:", a%b);
console.log("Power:", a**b);

// Comparison Operators

console.log(a>b);
console.log(a<b);
console.log(a==b);
console.log(a!=b);
console.log(a===b);

// Logical Operators

let age = 21;
let hasID = true;

console.log(age >= 18 && hasID);
console.log(age >= 18 || hasID);
console.log(!hasID);